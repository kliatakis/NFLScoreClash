// ─── INTERACTION TEST: DOES THE UI RESPOND TO A TAP? ────────────────────────
//
// Run with:  npm run interact      (part of `npm run check`)
//
// WHY THIS EXISTS
// ───────────────
// The smoke test renders every screen with renderToString, which proves the
// screens come up — but renderToString never runs an effect and never
// dispatches an event, so anything that only happens on a click is invisible
// to it. That gap is exactly where the ⓘ icons lived: they were spans with a
// `title`, which is a HOVER tooltip, so on a phone they looked tappable and
// did nothing. Every check in the repo passed the whole time.
//
// So this one mounts a component into a real DOM and clicks things.
//
// Scope is deliberately small. This is not a UI test suite; it covers the
// interactions where "renders fine" and "works" are different statements.
import { execSync } from "node:child_process";
import { join, resolve } from "node:path";
import { readFileSync, writeFileSync, rmSync } from "node:fs";
import { JSDOM } from "jsdom";

const ROOT = resolve(new URL("..", import.meta.url).pathname);
const OUT = join(ROOT, "dist-interact");

const dom = new JSDOM("<!doctype html><html><body><div id='root'></div></body></html>", { url: "https://scoreclash.local/" });
for (const k of ["window", "document", "navigator", "localStorage", "sessionStorage", "HTMLElement",
                 "Element", "Node", "getComputedStyle", "requestAnimationFrame", "MouseEvent", "Event"]) {
  try { Object.defineProperty(globalThis, k, { value: dom.window[k], configurable: true, writable: true }); }
  catch { /* best effort */ }
}
globalThis.matchMedia = dom.window.matchMedia = (q) => ({
  matches: false, media: q, onchange: null, addEventListener() {}, removeEventListener() {},
  addListener() {}, removeListener() {}, dispatchEvent() { return false; },
});
globalThis.IS_REACT_ACT_ENVIRONMENT = true;

// Regenerate the Firebase stub from the REAL module's export list, so adding
// an export there can never leave a silent hole here.
{
  const src = readFileSync(join(ROOT, "src/firebase.js"), "utf8");
  const fns = [...src.matchAll(/^export\s+(?:async\s+)?function\s+([A-Za-z0-9_]+)/gm)].map(m => m[1]);
  const consts = [...src.matchAll(/^export\s+const\s+([A-Za-z0-9_]+)\s*=\s*([^;\n]+)/gm)].map(m => [m[1], m[2].trim()]);
  const lines = [
    "// GENERATED by scripts/interact.mjs - do not edit by hand.",
    "//",
    "// A no-op stand-in for src/firebase.js, so the interaction test can mount",
    "// components whose effects would otherwise talk to Firestore. StandingsCard",
    "// persists its movement snapshot in an effect; without this the test would",
    "// open a live connection on every run, and with real credentials present it",
    "// would be writing to the actual league from a test.",
    "const unsub = () => () => {};",
    "",
  ];
  for (const n of fns) lines.push(`export const ${n} = async () => undefined;`);
  for (const [n, value] of consts) {
    // A plain constant keeps its real value; anything built from the Firebase
    // SDK becomes an inert object, and a subscription returns an unsubscribe.
    if (/^-?[\d.]+$/.test(value) || /^["'`]/.test(value)) lines.push(`export const ${n} = ${value};`);
    else if (n.startsWith("fsSubscribe")) lines.push(`export const ${n} = (...a) => unsub();`);
    else lines.push(`export const ${n} = {};`);
  }
  writeFileSync(join(ROOT, "scripts/interact-firebase-stub.js"), lines.join("\n") + "\n");
}

console.log("\n  compiling the component tree…");
execSync(`npx vite build --config scripts/vite.interact.config.mjs --ssr scripts/smoke-entry.jsx --outDir dist-interact --logLevel error`,
  { cwd: ROOT, stdio: "pipe" });

const React = await import("react");
const { createRoot } = await import("react-dom/client");
const { act } = React;
const { StandingsCard } = await import(join(OUT, "smoke-entry.js"));
const { REGULAR_SEASON_FIXTURES } = await import("../src/data/fixtures.js");

let total = 0, failures = 0;
const t = (name, cond, detail = "") => {
  total++;
  if (!cond) failures++;
  console.log(`${cond ? "  ok  " : "  FAIL"}  ${name}${detail ? `   [${detail}]` : ""}`);
};

// ── A league shaped like the real one: a tie (so the tiebreak ⓘ shows) and a
//    week bonus (so the bonus ⓘ shows). ──────────────────────────────────────
const members = ["a", "b", "c", "d"];
const allUsers = Object.fromEntries(members.map(u => [u, { username: u.toUpperCase(), avatar: null }]));
const allPredictions = Object.fromEntries(members.map(u => [u, { picks: {}, specials: {} }]));
const results = {};
const wk = (w) => REGULAR_SEASON_FIXTURES.filter(f => f.week === w);
for (const w of [1, 2]) {
  wk(w).forEach((f, i) => {
    results[f.id] = { homeScore: 27, awayScore: 13 };
    for (const u of members) {
      // Every home side wins, so "H" is right. "a" calls both weeks (two
      // bonuses); "b" calls week 1 only (one bonus). Two bonus ⓘ controls is
      // the minimum this test needs — one of its assertions is that opening a
      // second panel closes the first.
      if (u === "a") { allPredictions[u].picks[f.id] = { winner: "H" }; continue; }
      if (u === "b") { allPredictions[u].picks[f.id] = { winner: w === 1 ? "H" : (i % 3 ? "H" : "A") }; continue; }
      allPredictions[u].picks[f.id] = { winner: u === "d" ? (i % 2 ? "H" : "A") : (i % 4 ? "H" : "A") };
    }
  });
}
const league = { id: "L", name: "Test", members, adminIds: [], superAdminId: "a", settings: {}, reactions: {} };
const user = { uid: "d", username: "D" };

const container = dom.window.document.getElementById("root");
const root = createRoot(container);
await act(async () => {
  root.render(React.createElement(StandingsCard, {
    league, user, allUsers, allPredictions, results, specialResults: {},
  }));
});

const $ = (sel) => Array.from(container.querySelectorAll(sel));
const click = async (el) => { await act(async () => { el.dispatchEvent(new dom.window.MouseEvent("click", { bubbles: true })); }); };

// Two kinds of ⓘ exist and the difference matters. The ones in the table are
// CONTROLS and must be tappable. The one in the legend is an illustration
// inside the sentence "look for the ⓘ next to a name" — prose, not a control,
// and turning it into a button would be wrong.
const icons = $(".info-toggle");
t("the fixture produces at least two ⓘ controls, or the tests below are vacuous",
  icons.length >= 2, `${icons.length} found`);
const decorative = $(".tiebreak-info:not(.info-toggle)");
t("the standings render some ⓘ controls", icons.length > 0, `${icons.length} found`);

// ── THE BUG THIS FIXES ──────────────────────────────────────────────────────
t("every ⓘ control is a real button, not a hover-only span",
  icons.length > 0 && icons.every(el => el.tagName === "BUTTON"),
  icons.map(el => el.tagName).join(","));
t("...and each one still carries its tooltip for desktop hover",
  icons.every(el => (el.getAttribute("title") || "").length > 0));
t("...and announces itself to a screen reader",
  icons.every(el => (el.getAttribute("aria-label") || "").length > 0));
t("the legend's ⓘ stays decorative, and is hidden from screen readers",
  decorative.every(el => el.tagName === "SPAN" && el.getAttribute("aria-hidden") === "true"),
  `${decorative.length} decorative`);

// ── TAPPING ONE OPENS IT ────────────────────────────────────────────────────
t("nothing is expanded before anything is tapped", $(".standings-info").length === 0);

await click(icons[0]);
const opened = $(".standings-info");
t("tapping ⓘ opens a detail panel", opened.length === 1);
t("...containing the text that used to be hover-only",
  opened.length === 1 && opened[0].textContent.trim().length > 0,
  opened[0]?.textContent.slice(0, 60));
t("...and the button reports itself as expanded",
  $(".info-toggle")[0].getAttribute("aria-expanded") === "true");

// ── TAPPING IT AGAIN CLOSES IT ──────────────────────────────────────────────
await click($(".info-toggle")[0]);
t("tapping the same ⓘ again closes it", $(".standings-info").length === 0);

// ── ONLY ONE AT A TIME ──────────────────────────────────────────────────────
if (icons.length > 1) {
  await click($(".info-toggle")[0]);
  await click($(".info-toggle")[1]);
  t("opening a second ⓘ closes the first — never two panels at once",
    $(".standings-info").length === 1);
}

// ── AND IT CHANGED NOTHING ELSE ─────────────────────────────────────────────
// The panel is presentational. If a tap could alter a points total or the row
// order, that would be the one unacceptable outcome.
const pointsNow = $(".standings-pts").map(el => el.textContent);
const namesNow = $(".standings-name").map(el => el.textContent);
await click($(".info-toggle")[0]);
await click($(".info-toggle")[1]);
t("tapping ⓘ never changes anyone's points",
  JSON.stringify($(".standings-pts").map(el => el.textContent)) === JSON.stringify(pointsNow));
t("...and never reorders the table",
  JSON.stringify($(".standings-name").map(el => el.textContent)) === JSON.stringify(namesNow));

// Clean up the build this test made, so it leaves nothing behind for the
// deploy zip to pick up.
try { rmSync(OUT, { recursive: true, force: true }); } catch { /* fine */ }

console.log(`\n  ${total - failures}/${total} interaction checks passed.`);
if (failures) { console.error(`  ${failures} FAILED`); process.exit(1); }
