// ─── SHOUTOUT LINES ─────────────────────────────────────────────────────────
//
// One hardcoded joke told four times in the same week stops being a joke by
// the second telling. These are pools; lib/shoutouts.js picks from them.
//
// The pick is DETERMINISTIC, not random — see the note in lib/shoutouts.js.
// A line that re-rolled on every render would change while you were reading
// it, and the reaction someone left would end up attached to a different
// sentence than the one they reacted to.
//
// Placeholders, all optional in any given line:
//   {name}    who it's about — rendered bold
//   {game}    "Chicago Bears @ Carolina Panthers"
//   {winner}  the team that actually won, e.g. "Carolina Panthers"
//   {loser}   the team that lost
//   {score}   "24-17"
//
// ── HOUSE STYLE — read this before adding lines ────────────────────────────
//
// The tone is a group chat between friends who have known each other far too
// long. Blunt, sweary, personal about how badly someone picks. That's the
// brief and it's deliberate.
//
// The line that does NOT move: every insult aims at the PICK, the RECORD, or
// the EGO. Never at who someone is. Nothing about race, religion, nationality,
// sexuality, appearance, health, money or family. No slurs, ever.
//
// That isn't squeamishness, it's what makes the feature work. The app fires
// these automatically, at a named person, in a board their friends read, and
// nobody sees the specific line coming. "You are dreadful at this and everyone
// knows" survives that on a bad day. Anything about who somebody is doesn't,
// and one line landing wrong poisons the whole board.
//
// Also: vary the shape. Questions, mock sympathy, fake analysis, deadpan,
// pure abuse. A hundred lines that all open the same way read as one line.

